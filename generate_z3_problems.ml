let show_ir_structure name ir =
  Printf.printf "\n%s IR Structure:\n" name;
  Printf.printf "  Inputs: %d\n" (Hashtbl.length ir.ir_inputs);
  Hashtbl.iter (fun name value ->
    match value with
    | Input { id; width; _ } ->
        Printf.printf "    %s: input[%d] (width %d)\n" name id width
    | _ -> ()
  ) ir.ir_inputs;

  Printf.printf "  Outputs: %d\n" (Hashtbl.length ir.ir_outputs);
  Hashtbl.iter (fun name value ->
    match value with
    | Wire { id; width; _ } ->
        Printf.printf "    %s: wire[%d] (width %d)\n" name id width
    | Output { id; width; _ } ->
        Printf.printf "    %s: output[%d] (width %d)\n" name id width
    | _ -> ()
  ) ir.ir_outputs;

  Printf.printf "  Nodes: %d\n" (Hashtbl.length ir.ir_nodes);
  let node_types = Hashtbl.create 10 in
  Hashtbl.iter (fun _ node ->
    let op_name = match node.node_op with
      | Add _ -> "Add"
      | Sub _ -> "Sub"
      | Mul _ -> "Mul"
      | Div _ -> "Div"
      | And _ -> "And"
      | Or _ -> "Or"
      | Xor _ -> "Xor"
      | Not _ -> "Not"
      | Mux _ -> "Mux"
      | Pmux _ -> "Pmux"
      | Compare _ -> "Compare"
      | Shift _ -> "Shift"
      | Concat _ -> "Concat"
      | Extract _ -> "Extract"
      | ZeroExtend _ -> "ZeroExtend"
      | SignExtend _ -> "SignExtend"
      | Register _ -> "Register"
    in
    let count = try Hashtbl.find node_types op_name with Not_found -> 0 in
    Hashtbl.replace node_types op_name (count + 1)
  ) ir.ir_nodes;

  Printf.printf "  Node breakdown:\n";
  Hashtbl.iter (fun op_name count ->
    Printf.printf "    %s: %d\n" op_name count
  ) node_types

let generate_z3_problem vhdl_file sv_file module_name =
  Printf.printf "═══════════════════════════════════════════════════════════════\n";
  Printf.printf "Z3 SAT Problem: %s\n" module_name;
  Printf.printf "═══════════════════════════════════════════════════════════════\n";
  Printf.printf "VHDL: %s\n" (Filename.basename vhdl_file);
  Printf.printf "SV:   %s\n" (Filename.basename sv_file);
  Printf.printf "\n";

  (* Convert VHDL to IR *)
  Printf.printf "[1/2] Converting VHDL to IR...\n";
  let vhdl_ir_opt = convert_vhdl_file_to_ir vhdl_file in

  match vhdl_ir_opt with
  | None ->
      Printf.printf "  ✗ VHDL conversion failed\n\n";
      false
  | Some vhdl_ir ->
      Printf.printf "  ✓ VHDL IR generated\n";
      show_ir_structure "VHDL" vhdl_ir;

      (* Note: SV conversion would happen here *)
      Printf.printf "\n[2/2] SystemVerilog IR (would be generated by Verible)...\n";
      Printf.printf "  Note: Requires sv_verible_to_ir module\n";
      Printf.printf "  Expected structure: Similar to VHDL IR\n";

      (* Show what the Z3 problem would be *)
      Printf.printf "\n[3/3] Z3 Verification Problem:\n";
      Printf.printf "  Given:\n";
      Printf.printf "    • IR₁ (VHDL):  %d inputs, %d outputs, %d nodes\n"
        (Hashtbl.length vhdl_ir.ir_inputs)
        (Hashtbl.length vhdl_ir.ir_outputs)
        (Hashtbl.length vhdl_ir.ir_nodes);
      Printf.printf "    • IR₂ (SV):    To be generated\n";
      Printf.printf "\n";
      Printf.printf "  Prove:\n";
      Printf.printf "    ∀ input values, IR₁(inputs) = IR₂(inputs)\n";
      Printf.printf "\n";
      Printf.printf "  Method:\n";
      Printf.printf "    1. Create Z3 bitvector variables for all inputs\n";
      Printf.printf "    2. Symbolically execute IR₁ to get output expressions\n";
      Printf.printf "    3. Symbolically execute IR₂ to get output expressions\n";
      Printf.printf "    4. Assert outputs are equal: out₁ = out₂\n";
      Printf.printf "    5. Check satisfiability (UNSAT = equivalent)\n";
      Printf.printf "\n";
      Printf.printf "  Inputs to verify:\n";
      Hashtbl.iter (fun name value ->
        match value with
        | Input { width; _ } ->
            Printf.printf "    • %s: bitvector<%d>\n" name width
        | _ -> ()
      ) vhdl_ir.ir_inputs;
      Printf.printf "\n";
      Printf.printf "  Outputs to compare:\n";
      Hashtbl.iter (fun name value ->
        match value with
        | Wire { width; _ } | Output { width; _ } ->
            Printf.printf "    • %s: bitvector<%d>\n" name width
        | _ -> ()
      ) vhdl_ir.ir_outputs;
      Printf.printf "\n";

      true

